param(
    [string]$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path,
    [string]$OutHeader = ""
)

$ErrorActionPreference = "Stop"
$PSNativeCommandUseErrorActionPreference = $false

if ([string]::IsNullOrWhiteSpace($OutHeader)) {
    $OutHeader = Join-Path $RepoRoot "build\version_gen.h"
}

$versionFile = Join-Path $RepoRoot "VERSION"
$baseRaw = "1.0.0"
if (Test-Path $versionFile) {
    $line = (Get-Content $versionFile -TotalCount 1).Trim()
    if (-not [string]::IsNullOrWhiteSpace($line)) {
        $baseRaw = $line.TrimStart('v', 'V')
    }
}

$major = 1
$minor = 0
$patch = 0
$build = 0

if ($baseRaw -match '^(\d+)\.(\d+)(?:\.(\d+))?(?:\.(\d+))?') {
    $major = [int]$Matches[1]
    $minor = [int]$Matches[2]
    if ($Matches[3]) { $patch = [int]$Matches[3] }
    if ($Matches[4]) { $build = [int]$Matches[4] }
}

# Query git commit count and short SHA when git is available
$gitCommits = 0
$gitSha = "local"
$exactTag = ""
try {
    $cntOut = & git -C $RepoRoot rev-list --count HEAD 2>$null
    if ($LASTEXITCODE -eq 0 -and $cntOut -match '^\d+$') {
        $gitCommits = [int]$cntOut.Trim()
    }
    $shaOut = & git -C $RepoRoot rev-parse --short=7 HEAD 2>$null
    if ($LASTEXITCODE -eq 0 -and -not [string]::IsNullOrWhiteSpace($shaOut)) {
        $gitSha = $shaOut.Trim()
    }
    $tagOut = & git -C $RepoRoot describe --tags --exact-match HEAD 2>$null
    if ($LASTEXITCODE -eq 0 -and -not [string]::IsNullOrWhiteSpace($tagOut)) {
        $exactTag = $tagOut.Trim()
    }
} catch {
    # Git not installed or outside git worktree; keep safe defaults
}

$runNum = 0
if ($env:GITHUB_RUN_NUMBER -match '^\d+$') {
    $runNum = [int]$env:GITHUB_RUN_NUMBER
}

# Priority order:
# 1. Explicit E2_VERSION_OVERRIDE (e.g. workflow_dispatch input)
# 2. Git tag push (GITHUB_REF_TYPE == 'tag' and vX.Y.Z) or local HEAD sitting on vX.Y.Z tag
# 3. GitHub Actions CI run (MAJOR.MINOR.<GITHUB_RUN_NUMBER>)
# 4. Local build from VERSION file (MAJOR.MINOR.PATCH.<gitCommits>)
$override = $env:E2_VERSION_OVERRIDE
if (-not [string]::IsNullOrWhiteSpace($override) -and $override.Trim() -match '^v?(\d+)\.(\d+)\.(\d+)(?:\.(\d+))?$') {
    $major = [int]$Matches[1]
    $minor = [int]$Matches[2]
    $patch = [int]$Matches[3]
    $build = if ($Matches[4]) { [int]$Matches[4] } elseif ($runNum -gt 0) { $runNum } else { $gitCommits }
} elseif ($env:GITHUB_REF_TYPE -eq 'tag' -and $env:GITHUB_REF_NAME -match '^v?(\d+)\.(\d+)\.(\d+)(?:\.(\d+))?') {
    $major = [int]$Matches[1]
    $minor = [int]$Matches[2]
    $patch = [int]$Matches[3]
    $build = if ($Matches[4]) { [int]$Matches[4] } elseif ($runNum -gt 0) { $runNum } else { $gitCommits }
} elseif (-not [string]::IsNullOrWhiteSpace($exactTag) -and $exactTag -match '^v?(\d+)\.(\d+)\.(\d+)(?:\.(\d+))?$') {
    $major = [int]$Matches[1]
    $minor = [int]$Matches[2]
    $patch = [int]$Matches[3]
    $build = if ($Matches[4]) { [int]$Matches[4] } elseif ($runNum -gt 0) { $runNum } else { $gitCommits }
} elseif ($runNum -gt 0) {
    $patch = $patch + $runNum
    $build = $gitCommits
} else {
    $build = $gitCommits
}

# Clamp each 16-bit PE VERSIONINFO component to 0..65535
$major = [Math]::Min(65535, [Math]::Max(0, $major))
$minor = [Math]::Min(65535, [Math]::Max(0, $minor))
$patch = [Math]::Min(65535, [Math]::Max(0, $patch))
$build = [Math]::Min(65535, [Math]::Max(0, $build))

$semver = "$major.$minor.$patch"
$fileVer = "$major.$minor.$patch.$build"
$fullVer = "$semver ($gitSha)"
$tagVer = "v$semver"

$headerContent = @"
// Auto-generated by tools/gen_version.ps1 - do not edit by hand
#ifndef E2_VERSION_GEN_H
#define E2_VERSION_GEN_H

#define E2_VERSION_MAJOR $major
#define E2_VERSION_MINOR $minor
#define E2_VERSION_PATCH $patch
#define E2_VERSION_BUILD $build

#define E2_VERSION_SEMVER_STR "$semver"
#define E2_VERSION_SEMVER_WSTR L"$semver"
#define E2_VERSION_FILE_STR "$fileVer"
#define E2_VERSION_FILE_WSTR L"$fileVer"
#define E2_VERSION_FULL_STR "$fullVer"
#define E2_VERSION_FULL_WSTR L"$fullVer"
#define E2_GIT_SHA_STR "$gitSha"
#define E2_GIT_SHA_WSTR L"$gitSha"

#endif // E2_VERSION_GEN_H
"@ + "`r`n"

$outDir = Split-Path -Parent $OutHeader
if (-not (Test-Path $outDir)) {
    New-Item -ItemType Directory -Path $outDir -Force | Out-Null
}

$existing = ""
if (Test-Path $OutHeader) {
    $existing = [System.IO.File]::ReadAllText($OutHeader)
}
if ($existing -ne $headerContent) {
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($OutHeader, $headerContent, $utf8NoBom)
}

# Also write build\version_vars.cmd for batch scripts (e.g. build_installer.bat)
$varsCmdPath = Join-Path $outDir "version_vars.cmd"
$varsCmd = @"
@echo off
set "E2_SEMVER=$semver"
set "E2_FILEVER=$fileVer"
set "E2_TAG=$tagVer"
set "E2_SHA=$gitSha"
"@
$utf8NoBom2 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($varsCmdPath, $varsCmd, $utf8NoBom2)

# Emit GitHub Actions step outputs when running in CI
if (-not [string]::IsNullOrWhiteSpace($env:GITHUB_OUTPUT)) {
    Add-Content -Path $env:GITHUB_OUTPUT -Value "semver=$semver"
    Add-Content -Path $env:GITHUB_OUTPUT -Value "file_version=$fileVer"
    Add-Content -Path $env:GITHUB_OUTPUT -Value "tag=$tagVer"
    Add-Content -Path $env:GITHUB_OUTPUT -Value "sha=$gitSha"
    Add-Content -Path $env:GITHUB_OUTPUT -Value "full_version=$fullVer"
}

Write-Host "Explorer2 version: $fullVer [PE FILEVERSION $fileVer]"
Write-Host "::notice title=Explorer2 Version::$fullVer [PE $fileVer]"
$global:LASTEXITCODE = 0
exit 0
